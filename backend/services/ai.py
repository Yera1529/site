MANDATORY_SECTIONS = [
    ("дата_место", r"(\d{2}\.\d{2}\.\d{4}\s*г\.)|(\d{4}\s*год)"),
    ("ердр", r"(ЕРДР|ердр|Е\s*Р\s*Д\s*Р)"),
    ("статья_ук", r"(ст\.\s*\d+|стать[яией]\s*\d+).*(УК|Уголовн)"),
    ("нарушения", r"(нарушени[еяй]|бездействи|ненадлежащ)"),
    ("нормативные_акты", r"(ст\.\s*200\s*УПК|Уголовно-процессуальн)"),
    ("причинная_связь", r"(причин|способствовал|создал[оаи]?\s+условия|обусловил|повлекл)"),
    ("предлагаю", r"(ПРЕДЛАГАЮ|предлагаю)"),
    ("срок", r"(месячный срок|в течение месяца|не позднее|ч\.\s*2\s*ст\.\s*200)"),
    ("предупреждение", r"(479|664|КоАП|ответственност[ьи])"),
]


def validate_representation(text: str) -> dict:
    """Check generated text for all 9 mandatory markers.
    Returns {ok: bool, missing: [str], present: [str]}.
    """
    present, missing = [], []
    for label, pattern in MANDATORY_SECTIONS:
        if re.search(pattern, text, re.IGNORECASE):
            present.append(label)
        else:
            missing.append(label)
    return {"ok": len(missing) == 0, "missing": missing, "present": present}


def validate_law_citations(
    generated_text: str, retrieved_laws: list[dict]
) -> dict:
    """Check that cited articles in generated text match the retrieved law set."""
    cited_raw = re.findall(r"ст(?:атья|\.)\s*(\d+[\.\d]*)", generated_text, re.IGNORECASE)
    cited = sorted(set(cited_raw))

    provided_articles = set()
    for law in (retrieved_laws or []):
        art = law.get("article_number", "")
        if art:
            provided_articles.add(art)

    always_valid = {"200", "159", "479", "664"}
    unverified = [c for c in cited if c not in provided_articles and c not in always_valid]

    return {"cited": cited, "unverified": unverified}


def validate_norm_usage(generated_text: str, selected_laws: list[dict]) -> dict:
    """Check that EACH selected norm is actually cited in the generated document.

    Returns {all_used: bool, used: [...], unused: [...]}
    """
    used = []
    unused = []
    for law in (selected_laws or []):
        art_raw = law.get("article_number", "")
        law_name = law.get("law_title", law.get("law_name", ""))
        # Extract the PRIMARY article number only (first number in "Статья 182, пункт 1")
        # Skip punkt/podpunkt numbers to avoid false positives
        art_match = re.search(r'(\d+)', art_raw)
        if not art_match:
            unused.append({"law": law_name, "article": art_raw})
            continue
        art_num = art_match.group(1)
        # Match "ст.N" or "статья N" with word boundary AFTER the number
        # to prevent ст.1 from matching ст.188
        if re.search(rf'ст(?:атья|\.)\s*{art_num}(?!\d)', generated_text, re.IGNORECASE):
            used.append({"law": law_name, "article": art_raw})
        else:
            unused.append({"law": law_name, "article": art_raw})
    return {
        "all_used": len(unused) == 0,
        "used": used,
        "unused": unused,
    }


def validate_addressee(generated_text: str) -> dict:
    """Check that the addressee is NOT a law enforcement body (self-addressing).

    Returns {ok: bool, reason: str}
    """
    # Check first 500 chars (header area) for bad addressee patterns
    header = generated_text[:800].lower()
    bad_patterns = [
        (r"начальнику\s+(уп|управления\s+полиции|оп|ровд|увд|говд|гувд)", "Начальнику управления полиции"),
        (r"начальнику\s+следственного", "Начальнику следственного органа"),
        (r"руководителю\s+следственного", "Руководителю следственного органа"),
        (r"прокурору", "Прокурору"),
        (r"начальнику\s+дежурной\s+части", "Начальнику дежурной части"),
    ]
    for pattern, label in bad_patterns:
        if re.search(pattern, header, re.IGNORECASE):
            return {
                "ok": False,
                "reason": f"Адресат — правоохранительный орган ({label}). "
                          f"Представление должно быть адресовано организации, "
                          f"чьи нарушения способствовали преступлению.",
            }
    return {"ok": True, "reason": ""}


class AIService:
    def __init__(self):
        settings = get_settings()
        self.api_key = settings.ai_api_key
        self.model_name = settings.ai_model  # e.g. "gemini-2.5-flash"

        if self.api_key:
            # Direct Gemini API key authentication
            self._client = genai.Client(api_key=self.api_key)
            logger.info("AIService: using Gemini API key auth, model=%s", self.model_name)
        else:
            # Vertex AI with service account (GOOGLE_APPLICATION_CREDENTIALS)
            project = settings.vertex_ai_project
            location = settings.vertex_ai_location
            self._client = genai.Client(
                vertexai=True,
                project=project,
                location=location,
            )
            logger.info(
                "AIService: using Vertex AI auth, project=%s, location=%s, model=%s",
                project, location, self.model_name,
            )

