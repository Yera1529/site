def run():
    # warmup / readiness
    try:
        st, stats = _req("GET", "/api/rag-laws/stats", timeout=120)
        print(f"index: {stats}")
    except Exception as e:
        print(f"stats failed: {e}")

    # create throwaway matter
    _, matter = _req("POST", "/api/matters", {"name": "__RAG_AUDIT__", "description": "init"})
    mid = matter["id"]
    print(f"matter: {mid}\n")
    print(f"{'#':>2} {'домен':<26} {'st':>3} {'norms':>5} {'clean':>5} {'hit':>4} {'sec':>5}  top-3")
    print("-" * 130)

    results = []
    for i, c in enumerate(CASES, 1):
        rec = {"n": i, "domain": c["domain"], "status": None, "norms": 0,
               "clean": None, "hit": None, "sec": 0.0, "top": [], "banned_hits": [], "koap": False, "error": None}
        try:
            _req("PUT", f"/api/matters/{mid}", {"description": c["fabula"], "custom_instructions": ""})
            t0 = time.time()
            st, laws = _req("POST", "/api/search-laws", {
                "matter_id": mid, "query": "",
                "violations": [c["violation"]], "addressee": c["addressee"],
            })
            rec["sec"] = round(time.time() - t0, 1)
            rec["status"] = st
            laws = laws or []
            top5 = laws[:5]
            rec["norms"] = len(laws)
            titles = [(l.get("law_title", "") or "") for l in top5]
            texts = [((l.get("law_title", "") or "") + " " + (l.get("text", "") or "")).lower() for l in top5]
            # cleanliness
            banned_hits = []
            for t in titles:
                tl = t.lower()
                for b in BANNED:
                    if b in tl:
                        banned_hits.append(t)
            rec["banned_hits"] = sorted(set(banned_hits))
            rec["clean"] = len(banned_hits) == 0
            rec["koap"] = any("административных правонарушен" in tl for tl in texts)
            # relevance hint
            exp = [e.lower() for e in c.get("expect_any", [])]
            rec["hit"] = any(any(e in tx for e in exp) for tx in texts) if exp else None
            rec["top"] = [f"{(l.get('law_title','') or '')[:38]}|ст.{l.get('article_number','')}" for l in top5[:3]]
        except urllib.error.HTTPError as he:
            rec["status"] = he.code
            rec["error"] = he.read().decode("utf-8", "ignore")[:200]
        except Exception as e:
            rec["error"] = f"{type(e).__name__}: {e}"[:200]

        results.append(rec)
        clean_s = "OK" if rec["clean"] else ("BAN" if rec["clean"] is False else "-")
        hit_s = "Y" if rec["hit"] else ("n" if rec["hit"] is False else "-")
        top_s = " ; ".join(rec["top"]) if rec["top"] else (rec["error"] or "")
        print(f"{i:>2} {c['domain']:<26} {str(rec['status']):>3} {rec['norms']:>5} {clean_s:>5} {hit_s:>4} {rec['sec']:>5}  {top_s[:80]}")

    # cleanup
    try:
        _req("DELETE", f"/api/matters/{mid}")
        print(f"\nmatter {mid} deleted")
    except Exception as e:
        print(f"\ncleanup failed: {e}")

    # aggregate
    ok = [r for r in results if r["status"] == 200 and r["error"] is None]
    crashed = [r for r in results if r["status"] != 200 or r["error"]]
    empty = [r for r in ok if r["norms"] == 0]
    dirty = [r for r in ok if r["clean"] is False]
    hits = [r for r in ok if r["hit"]]
    avg_sec = round(sum(r["sec"] for r in ok) / len(ok), 1) if ok else 0
    print("\n" + "=" * 60)
    print(f"всего кейсов:        {len(results)}")
    print(f"успешно (200):       {len(ok)}")
    print(f"крашей/ошибок:       {len(crashed)}")
    print(f"пустых результатов:  {len(empty)}")
    print(f"чистых (без УК/УПК): {len(ok) - len(dirty)}/{len(ok)}")
    print(f"с запрещёнными:      {len(dirty)}")
    print(f"релевант. попадание: {len(hits)}/{len(ok)} (мягкий хинт)")
    print(f"средн. время:        {avg_sec} сек")
    if dirty:
        print("\nЗАГРЯЗНЁННЫЕ КЕЙСЫ:")
        for r in dirty:
            print(f"  #{r['n']} {r['domain']}: {r['banned_hits']}")
    if crashed:
        print("\nКРАШИ:")
        for r in crashed:
            print(f"  #{r['n']} {r['domain']}: status={r['status']} {r['error']}")

    with open("eval/api_demo_results.json", "w", encoding="utf-8") as f:
        json.dump(results, f, ensure_ascii=False, indent=2)
    print("\nдетали → eval/api_demo_results.json")


if __name__ == "__main__":
    run()
